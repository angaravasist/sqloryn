#!/usr/bin/env bash
# Measure "open -> process exists" for the built SQLoryn.app and write docs/evidence/launch-<arch>.md.
#
# What this measures: wall-clock time from invoking `open` until a process named Sqloryn is visible to pgrep.
# What it does NOT measure: window shown, first paint, or input readiness. It is not a disk-cold measurement
# (no `purge`, which needs root); each run only starts from "no Sqloryn process running".
# Real numbers only: any failure is recorded as a skip with the reason; nothing is estimated.
#
# Usage: scripts/measure_app_launch.sh [RUNS=3]
#   SQLORYN_APP=/path/to/SQLoryn.app  override bundle (default artifacts/macos/<arch>/SQLoryn.app)
#   SQLORYN_LAUNCH_TIMEOUT_S=30       per-run timeout
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RUNS="${1:-3}"
TIMEOUT_S="${SQLORYN_LAUNCH_TIMEOUT_S:-30}"
PROC="Sqloryn"

case "$RUNS" in ''|*[!0-9]*) echo "RUNS must be a positive integer" >&2; exit 2 ;; esac
[[ "$RUNS" -ge 1 ]] || { echo "RUNS must be >= 1" >&2; exit 2; }

MACHINE="$(uname -m)"
case "$MACHINE" in
  arm64) SHORT=arm64; RID=osx-arm64 ;;
  x86_64) SHORT=x64; RID=osx-x64 ;;
  *) SHORT="$MACHINE"; RID="unknown" ;;
esac
APP="${SQLORYN_APP:-$ROOT/artifacts/macos/$RID/SQLoryn.app}"
OUT="$ROOT/docs/evidence/launch-$SHORT.md"
mkdir -p "$ROOT/docs/evidence"

MACOS_VERSION="$(sw_vers -productVersion 2>/dev/null || echo unknown) ($(sw_vers -buildVersion 2>/dev/null || echo unknown))"
HW_MODEL="$(sysctl -n hw.model 2>/dev/null || echo unknown)"
CHIP="$(sysctl -n machdep.cpu.brand_string 2>/dev/null || echo unknown)"
COMMIT="$(git -C "$ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)"
STAMP="$(date -u +%Y-%m-%dT%H:%M:%SZ)"

write_report() { # $1 = status line, $2 = results body
  {
    echo "# Launch measurement ($SHORT)"
    echo
    echo "Generated by \`scripts/measure_app_launch.sh\` at $STAMP; git HEAD \`$COMMIT\` (the bundle is whatever was last built; HEAD does not prove it matches). Do not edit numbers by hand."
    echo
    echo "## Environment"
    echo
    echo "- \`uname -m\`: $MACHINE"
    echo "- macOS: $MACOS_VERSION"
    echo "- Hardware model: $HW_MODEL"
    echo "- CPU: $CHIP"
    echo "- Bundle: \`${APP#"$ROOT"/}\`"
    echo
    echo "## Method and limits"
    echo
    echo "Time from invoking \`open\` until \`pgrep -x $PROC\` finds a process (polled every ~20 ms; timeout ${TIMEOUT_S}s)."
    echo "Each run starts with no $PROC process running and terminates the process it started afterwards."
    echo "This is process-start latency only: it is **not** window-visible, first-paint or input-ready time, and it is **not**"
    echo "disk-cold (no cache purge, which needs root). No VoiceOver, screenshot or SQL activity is involved."
    echo
    echo "## Result"
    echo
    echo "$1"
    echo
    echo "$2"
  } > "$OUT"
  echo "Wrote $OUT"
}

skip() {
  echo "SKIP: $1" >&2
  write_report "**Skip:** $1" "No numbers were recorded."
  exit 0
}

[[ "$MACHINE" == "arm64" || "$MACHINE" == "x86_64" ]] || skip "unsupported machine type $MACHINE"
command -v python3 >/dev/null 2>&1 || skip "python3 not available for monotonic timing"
command -v open >/dev/null 2>&1 || skip "open(1) not available"
[[ -d "$APP" ]] || skip "bundle not found at ${APP#"$ROOT"/}; run scripts/build_macos_app.sh first"
if pgrep -x "$PROC" >/dev/null 2>&1; then
  skip "a $PROC process is already running; refusing to terminate a process this script did not start"
fi

mono_ms() { python3 -c 'import time; print(time.monotonic_ns() // 1000000)'; }

TIMES=()
ROWS=""
for i in $(seq 1 "$RUNS"); do
  start="$(mono_ms)"
  if ! open "$APP" 2>/tmp/sqloryn-open.err; then
    reason="$(tr '\n' ' ' < /tmp/sqloryn-open.err | cut -c1-200)"
    rm -f /tmp/sqloryn-open.err
    skip "open failed on run $i: ${reason:-no message}"
  fi
  rm -f /tmp/sqloryn-open.err
  pid=""
  while :; do
    pid="$(pgrep -x "$PROC" 2>/dev/null | head -n1 || true)"
    now="$(mono_ms)"
    [[ -n "$pid" ]] && break
    if (( now - start > TIMEOUT_S * 1000 )); then
      skip "no $PROC process after ${TIMEOUT_S}s on run $i"
    fi
    sleep 0.02
  done
  elapsed=$(( now - start ))
  TIMES+=("$elapsed")
  ROWS+="| $i | $elapsed |"$'\n'
  # Terminate only the process we observed starting, then wait for it to exit before the next run.
  kill -TERM "$pid" 2>/dev/null || true
  for _ in $(seq 1 200); do
    kill -0 "$pid" 2>/dev/null || break
    sleep 0.05
  done
  if kill -0 "$pid" 2>/dev/null; then
    kill -KILL "$pid" 2>/dev/null || true
    skip "process $pid did not exit after TERM; stopped after run $i"
  fi
  sleep 1
done

SORTED=($(printf '%s\n' "${TIMES[@]}" | sort -n))
N=${#SORTED[@]}
MAX=${SORTED[$((N - 1))]}
MIN=${SORTED[0]}
if (( N % 2 == 1 )); then
  MEDIAN=${SORTED[$((N / 2))]}
else
  MEDIAN=$(( (SORTED[N / 2 - 1] + SORTED[N / 2]) / 2 ))
fi

BODY="| Run | open → process exists (ms) |"$'\n'"|---:|---:|"$'\n'"$ROWS"$'\n'"Runs: $N · min ${MIN} ms · **median ${MEDIAN} ms** · **max ${MAX} ms**"
write_report "**Measured** ($N runs)." "$BODY"
